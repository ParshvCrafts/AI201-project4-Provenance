def measure(text: str) -> dict:
    model = detector.model_signal(text)
    style = stylometry.style_signal(text)
    combined = scoring.combine_signals(model, style)
    guess, _ = scoring.score_to_label(combined)
    return {
        "ppl": round(detector.perplexity(text), 1),
        "model": model,
        "spread": round(stylometry.sentence_length_spread(text), 3),
        "ttr": round(stylometry.type_token_ratio(text), 3),
        "punct": round(stylometry.punctuation_density(text), 3),
        "style": round(style, 4),
        "combined": round(combined, 4),
        "guess": guess,
    }


if __name__ == "__main__":
    cols = ["ppl", "model", "spread", "ttr", "punct", "style", "combined", "guess"]
    print(f"{'input':<15}" + "".join(f"{c:>10}" for c in cols))
    for name, text in CALIBRATION.items():
        row = measure(text)
